"""Local-only ground-truth server for real visual-interaction E2E tests.

This is an evaluation target, not a WinPilot capability.  It records browser
events generated by a real pointer sequence so the E2E assertion does not rely
on the agent reporting its own success.
"""
from __future__ import annotations

import json
import sys
import threading
import time
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path
from typing import Any
from urllib.parse import urlsplit


ROOT = Path(__file__).resolve().parent
TARGET = ROOT / "visual_interaction_target.html"
STATE_LOCK = threading.Lock()
STATE: dict[str, Any] = {
    "ready": True,
    "success": False,
    "events": [],
    "started_at": time.time(),
}


class Handler(BaseHTTPRequestHandler):
    server_version = "WinPilotVisualE2E/1"

    def log_message(self, _format: str, *_args: Any) -> None:
        return

    def _send_json(self, status: int, value: Any) -> None:
        data = json.dumps(value, ensure_ascii=False).encode("utf-8")
        self.send_response(status)
        self.send_header("Content-Type", "application/json; charset=utf-8")
        self.send_header("Content-Length", str(len(data)))
        self.send_header("Cache-Control", "no-store")
        self.end_headers()
        self.wfile.write(data)

    def do_GET(self) -> None:  # noqa: N802 - BaseHTTPRequestHandler API
        path = urlsplit(self.path).path
        if path == "/state":
            with STATE_LOCK:
                snapshot = json.loads(json.dumps(STATE))
            self._send_json(200, snapshot)
            return
        if path in {"/", "/visual_interaction_target.html"}:
            data = TARGET.read_bytes()
            self.send_response(200)
            self.send_header("Content-Type", "text/html; charset=utf-8")
            self.send_header("Content-Length", str(len(data)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(data)
            return
        self._send_json(404, {"ok": False, "error": "not found"})

    def do_POST(self) -> None:  # noqa: N802 - BaseHTTPRequestHandler API
        if urlsplit(self.path).path != "/event":
            self._send_json(404, {"ok": False, "error": "not found"})
            return
        try:
            size = min(16_384, max(0, int(self.headers.get("Content-Length") or 0)))
            event = json.loads(self.rfile.read(size).decode("utf-8"))
            if not isinstance(event, dict):
                raise ValueError("event must be an object")
        except Exception as exc:
            self._send_json(400, {"ok": False, "error": str(exc)})
            return
        safe = {
            key: event.get(key)
            for key in (
                "case_id", "type", "trusted", "pointer_type", "client_x", "client_y",
                "screen_x", "screen_y", "move_count", "succeeded", "token_center_x",
                "token_center_y", "token_left", "token_top", "token_right", "token_bottom",
                "target_left", "target_top", "target_right", "target_bottom",
                "viewport_width", "viewport_height",
            )
        }
        safe["received_at"] = time.time()
        with STATE_LOCK:
            STATE["events"].append(safe)
            STATE["events"] = STATE["events"][-100:]
            if (
                safe.get("type") == "pointerup"
                and safe.get("trusted") is True
                and safe.get("succeeded") is True
                and int(safe.get("move_count") or 0) >= 2
            ):
                STATE["success"] = True
                STATE["completed_at"] = time.time()
                STATE["case_id"] = str(safe.get("case_id") or "")
        self._send_json(200, {"ok": True})


def main() -> None:
    port = int(sys.argv[1]) if len(sys.argv) > 1 else 8879
    server = ThreadingHTTPServer(("127.0.0.1", port), Handler)
    print(json.dumps({"ready": True, "port": port}), flush=True)
    server.serve_forever(poll_interval=0.1)


if __name__ == "__main__":
    main()
